CATEGORIES = {"data": "data", "engineering": "engineering", "machine learning": "machine_learning",
              "machine_learning": "machine_learning", "ml": "machine_learning", "ai": "machine_learning",
              "business": "business"}


def normalize_category(value: str) -> str:
    return CATEGORIES.get(value.strip().lower().replace("-", " "), "engineering")


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:70] or "topic"


# --- Curated content -------------------------------------------------------------------------------


async def _upsert_curated(db: AsyncSession, content: CuratedRoadmap, roadmap: Roadmap | None) -> None:
    if roadmap is None:
        roadmap = Roadmap(slug=content.slug, source="curated", owner_id=None)
        db.add(roadmap)
    roadmap.role, roadmap.category, roadmap.version = content.role, content.category, content.version
    roadmap.description, roadmap.note = content.description, content.note
    roadmap.status, roadmap.progress = "ready", 1.0
    await db.flush()

    order = [n.key for n in content.nodes]
    prereqs = {n.key: list(n.prerequisites) for n in content.nodes}
    positions = layout(order, prereqs)
    existing = {n.key: n for n in (await db.execute(
        select(RoadmapNode).where(RoadmapNode.roadmap_id == roadmap.id))).scalars().all()}
    for i, n in enumerate(content.nodes):
        node = existing.pop(n.key, None) or RoadmapNode(roadmap_id=roadmap.id, key=n.key)
        if node.title != n.title or node.description != n.description:
            node.embedding = None  # recomputed on demand
        node.position, node.title, node.description, node.optional = i, n.title, n.description, n.optional
        node.prerequisites, node.resources = list(n.prerequisites), list(n.resources)
        node.x, node.y = positions[n.key]
        db.add(node)
    for stale in existing.values():
        await db.delete(stale)


async def ensure_curated(db: AsyncSession) -> None:
    """Idempotent: inserts missing curated roadmaps and updates those whose content version changed."""
    rows = {r.slug: r for r in (await db.execute(select(Roadmap).where(Roadmap.source == "curated"))).scalars()}
    todo = [c for c in CURATED if c.slug not in rows or rows[c.slug].version != c.version]
    if not todo:
        return
    try:
        for content in todo:
            await _upsert_curated(db, content, rows.get(content.slug))
        await db.commit()
    except IntegrityError:  # another request seeded at the same moment
        await db.rollback()


# --- Access -----------------------------------------------------------------------------------------


def _visible(user_id: str):
    return or_(Roadmap.owner_id.is_(None), Roadmap.owner_id == user_id)


async def _visible_roadmap(db: AsyncSession, user_id: str, roadmap_id: str) -> Roadmap:
    r = await db.get(Roadmap, roadmap_id)
    if r is None or (r.owner_id is not None and r.owner_id != user_id):
        raise NotFoundError("Roadmap not found.")
    return r


async def _nodes(db: AsyncSession, roadmap_id: str) -> list[RoadmapNode]:
    return list((await db.execute(select(RoadmapNode).where(RoadmapNode.roadmap_id == roadmap_id)
                                  .order_by(RoadmapNode.position))).scalars().all())


# --- Status from evidence ---------------------------------------------------------------------------

_CONCEPT_STATUS = {  # learning-profile status -> (roadmap status, progress)
    "good_evidence": ("completed", 100),
    "developing": ("in_progress", 60),
    "needs_practice": ("in_progress", 30),
}
_MANUAL_PROGRESS = {"known": 100, "completed": 100, "not_started": 0}


async def _ensure_embeddings(db: AsyncSession, nodes: list[RoadmapNode]) -> None:
    missing = [n for n in nodes if n.embedding is None]
    if not missing:
        return
    vectors = await get_embedder().embed_documents(
        [f"{n.title}: {n.description}" if n.description else n.title for n in missing])
    for node, vec in zip(missing, vectors, strict=True):
        node.embedding = vec
    await db.commit()


_STOP = {"the", "and", "for", "with", "from", "into", "its", "their", "your", "how", "what", "why", "basics",
         "introduction", "intro", "fundamentals", "foundations", "using", "use"}


def _stems(text: str) -> set[str]:
    return {w[:6] for w in re.findall(r"[a-z0-9]+", text.lower()) if len(w) >= 3 and w not in _STOP}


def concept_fits(node_text: str, concept_name: str, similarity: float) -> bool:
    """Embedding similarity alone is not discriminative enough with a small model (unrelated pairs often
    score 0.85+), so a match needs the concept's words in the topic text, or a very high similarity."""
    words = _stems(concept_name)
    lexical = bool(words) and words <= _stems(node_text)
    s = get_settings()
    return (lexical and similarity >= s.roadmap_concept_lexical_min_score) or similarity >= s.roadmap_concept_min_score


async def _concept_matches(db: AsyncSession, user_id: str, nodes: list[RoadmapNode]) -> dict[str, Concept]:
    """Best matching concept of the student's own courses for each node, when it clearly fits.

    This is how studying a course moves the roadmap: e.g. a 'Backpropagation' concept in an uploaded
    lecture counts toward a 'Neural networks and deep learning' node that mentions backpropagation.
    """
    concepts = (await db.execute(select(Concept).where(Concept.user_id == user_id,
                                                       Concept.embedding.is_not(None)))).scalars().all()
    if not concepts or not nodes:
        return {}
    await _ensure_embeddings(db, nodes)
    c = np.array([list(x.embedding) for x in concepts], dtype=np.float32)
    n = np.array([list(x.embedding) for x in nodes], dtype=np.float32)
    c /= np.linalg.norm(c, axis=1, keepdims=True) + 1e-9
    n /= np.linalg.norm(n, axis=1, keepdims=True) + 1e-9
    sims = n @ c.T
    matches = {}
    for i, node in enumerate(nodes):
        text = f"{node.title} {node.description}"
        for j in np.argsort(-sims[i]):
            if concept_fits(text, concepts[j].name, float(sims[i, j])):
                matches[node.id] = concepts[j]
                break
    return matches


async def _session_results(db: AsyncSession, session_ids: set[str]) -> dict[str, list[str]]:
    """Verdicts of graded answers per study session."""
    if not session_ids:
        return {}
    rows = (await db.execute(
        select(Activity.session_id, Evaluation.verdict)
        .join(Attempt, Attempt.activity_id == Activity.id)
        .join(Evaluation, Evaluation.attempt_id == Attempt.id)
        .where(Activity.session_id.in_(session_ids))
    )).all()
    out: dict[str, list[str]] = {}
    for sid, verdict in rows:
        out.setdefault(sid, []).append(verdict)
    return out


def _from_sessions(verdicts: list[str], started: bool) -> tuple[str, int, str | None]:
    correct = verdicts.count("correct")
    partial = verdicts.count("partially_correct")
    if correct >= 2:
        return "completed", 100, f"{correct} correct answers in study sessions on this topic"
    if verdicts:
        return "in_progress", min(90, 20 + 25 * correct + 10 * partial), \
            f"{len(verdicts)} answer(s) graded in study sessions on this topic, {correct} correct"
    if started:
        return "in_progress", 10, "Study session started"
    return "not_started", 0, None


async def _node_states(db: AsyncSession, user_id: str, nodes: list[RoadmapNode]) -> list[NodeOut]:
    progress = {p.node_id: p for p in (await db.execute(select(RoadmapNodeProgress).where(
        RoadmapNodeProgress.user_id == user_id, RoadmapNodeProgress.node_id.in_([n.id for n in nodes])
    ))).scalars().all()}
    matches = await _concept_matches(db, user_id, nodes)
    for node_id, p in progress.items():  # a concept chosen when a course session was started wins
        if p.concept_id and (concept := await db.get(Concept, p.concept_id)):
            matches[node_id] = concept
    concept_progress = {cp.concept_id: cp for cp in (await db.execute(select(ConceptProgress).where(
        ConceptProgress.user_id == user_id,
        ConceptProgress.concept_id.in_([c.id for c in matches.values()]),
    ))).scalars().all()} if matches else {}
    all_sessions = {sid for p in progress.values() for sid in (p.session_ids or [])}
    verdicts_by_session = await _session_results(db, all_sessions)
    courses = {c.id: c.title for c in (await db.execute(select(Course).where(
        Course.id.in_({c.course_id for c in matches.values()})))).scalars()} if matches else {}

    key_to_id = {n.key: n.id for n in nodes}
    out = []
    for node in nodes:
        p = progress.get(node.id)
        sessions = list(p.session_ids or []) if p else []
        verdicts = [v for sid in sessions for v in verdicts_by_session.get(sid, [])]
        status, pct, summary = _from_sessions(verdicts, bool(sessions))

        concept = matches.get(node.id)
        cp = concept_progress.get(concept.id) if concept else None
        if cp is not None:
            c_status, c_pct = _CONCEPT_STATUS.get(cp.status, ("in_progress" if cp.evidence_count else "not_started",
                                                              15 if cp.evidence_count else 0))
            if c_pct > pct:
                status, pct = c_status, c_pct
                summary = f"From '{concept.name}' in your course {courses.get(concept.course_id, '')}: {cp.reason}" \
                    .strip().rstrip(":")
        manual = p.manual_status if p else None
        if manual:
            status = manual
            pct = _MANUAL_PROGRESS.get(manual, max(pct, 10))
            summary = {"known": "You marked this topic as already known.",
                       "completed": "You marked this topic as completed.",
                       "not_started": "You reset this topic to not started.",
                       }.get(manual, "You marked this topic as in progress.") + (f" Evidence: {summary}" if summary
                                                                                 else "")
        out.append(NodeOut(
            id=node.id, key=node.key, title=node.title, description=node.description, order=node.position,
            type="optional" if node.optional else "core", status=status, progress=pct,
            prerequisites=[key_to_id[k] for k in node.prerequisites if k in key_to_id],
            resources=list(node.resources or []), position=Position(x=node.x, y=node.y),
            concept_id=concept.id if concept else None, concept_name=concept.name if concept else None,
            course_id=concept.course_id if concept else None, evidence_summary=summary, manual_override=bool(manual),
        ))
    return out


def _overall(states: list[NodeOut]) -> int:
    core = [s for s in states if s.type == "core"] or states
    return round(sum(s.progress for s in core) / len(core)) if core else 0


# --- Output -----------------------------------------------------------------------------------------


def _summary(r: Roadmap, nodes: list[RoadmapNode], progress: int, following: bool) -> RoadmapSummaryOut:
    return RoadmapSummaryOut(
        id=r.id, slug=r.slug, role=r.role, category=r.category, description=r.description,
        source=r.source, status=r.status,
        progress=progress, topic_count=len(nodes), following=following, created_at=r.created_at,
        core_topics=[n.title for n in nodes if not n.optional][:4],
        optional_topics=[n.title for n in nodes if n.optional][:2],
    )


async def _following(db: AsyncSession, user_id: str) -> set[str]:
    return set((await db.execute(select(UserRoadmap.roadmap_id).where(UserRoadmap.user_id == user_id))).scalars())


async def list_roadmaps(db: AsyncSession, user_id: str) -> list[RoadmapSummaryOut]:
    await ensure_curated(db)
    roadmaps = (await db.execute(select(Roadmap).where(_visible(user_id))
                                 .order_by(Roadmap.source.desc(), Roadmap.created_at.desc()))).scalars().all()
    following = await _following(db, user_id)
    out = []
    for r in roadmaps:  # generated first (newest), then curated
        nodes = await _nodes(db, r.id)
        # Progress only where the student engaged; cheap for the rest.
        has_progress = r.id in following or r.owner_id == user_id
        progress = _overall(await _node_states(db, user_id, nodes)) if has_progress and nodes else 0
        out.append(_summary(r, nodes, progress, r.id in following))
    return out


async def get_roadmap(db: AsyncSession, user_id: str, roadmap_id: str) -> RoadmapOut:
    await ensure_curated(db)
    r = await _visible_roadmap(db, user_id, roadmap_id)
    nodes = await _nodes(db, r.id)
    states = await _node_states(db, user_id, nodes) if nodes else []
    following = r.id in await _following(db, user_id)
    base = _summary(r, nodes, _overall(states), following)
    return RoadmapOut(**base.model_dump(), note=r.note, goal=r.goal, version=r.version,
                      generation_progress=r.progress, stage=r.stage, error=r.error, nodes=states)


# --- Generation -------------------------------------------------------------------------------------


async def request_generation(db: AsyncSession, user: User, data: GenerateIn) -> RoadmapOut:
    busy = (await db.execute(select(func.count()).select_from(Roadmap).where(
        Roadmap.owner_id == user.id, Roadmap.status == "generating"))).scalar_one()
    if busy:
        raise ConflictError("A roadmap is already being generated for you. Wait for it to finish first.")
    total = (await db.execute(select(func.count()).select_from(Roadmap).where(
        Roadmap.owner_id == user.id))).scalar_one()
    if total >= MAX_GENERATED:
        raise ConflictError(f"You can keep up to {MAX_GENERATED} generated roadmaps. Delete one to make room.")
    r = Roadmap(owner_id=user.id, source="generated", role=data.role.strip(),
                category=normalize_category(data.category), goal=data.goal.strip() or None, description="",
                note=GENERATED_NOTE, status="generating",
                progress=0.0, stage="Queued")
    db.add(r)
    await db.flush()
    await enqueue(db, GENERATE_JOB, {"roadmap_id": r.id}, user_id=user.id, subject=f"roadmap:{r.id}", priority=5)
    db.add(UserRoadmap(user_id=user.id, roadmap_id=r.id, roadmap_version=1, last_opened_at=utcnow()))
    await db.commit()
    return await get_roadmap(db, user.id, r.id)


async def retry_generation(db: AsyncSession, user_id: str, roadmap_id: str) -> RoadmapOut:
    r = await _visible_roadmap(db, user_id, roadmap_id)
    if r.owner_id != user_id or r.status != "failed":
        raise ConflictError("Only a generated roadmap that failed can be generated again.")
    r.status, r.progress, r.stage, r.error = "generating", 0.0, "Queued", None
    await enqueue(db, GENERATE_JOB, {"roadmap_id": r.id}, user_id=user_id, subject=f"roadmap:{r.id}", priority=5)
    await db.commit()
    return await get_roadmap(db, user_id, r.id)


async def delete_roadmap(db: AsyncSession, user_id: str, roadmap_id: str) -> None:
    r = await _visible_roadmap(db, user_id, roadmap_id)
    if r.owner_id != user_id:
        raise ConflictError("Curated roadmaps cannot be deleted. You can stop following them instead.")
    await db.delete(r)
    await db.commit()


# --- Following, overrides and sessions ---------------------------------------------------------------


async def follow(db: AsyncSession, user_id: str, roadmap_id: str) -> None:
    r = await _visible_roadmap(db, user_id, roadmap_id)
    row = (await db.execute(select(UserRoadmap).where(UserRoadmap.user_id == user_id,
                                                      UserRoadmap.roadmap_id == r.id))).scalar_one_or_none()
    if row is None:
        db.add(UserRoadmap(user_id=user_id, roadmap_id=r.id, roadmap_version=r.version, last_opened_at=utcnow()))
    else:
        row.last_opened_at, row.roadmap_version = utcnow(), r.version
    await db.flush()


async def unfollow(db: AsyncSession, user_id: str, roadmap_id: str) -> None:
    await _visible_roadmap(db, user_id, roadmap_id)
    await db.execute(delete(UserRoadmap).where(UserRoadmap.user_id == user_id, UserRoadmap.roadmap_id == roadmap_id))
    await db.commit()


async def _node(db: AsyncSession, user_id: str, roadmap_id: str, node_id: str) -> tuple[Roadmap, RoadmapNode]:
    r = await _visible_roadmap(db, user_id, roadmap_id)
    node = await db.get(RoadmapNode, node_id)
    if node is None or node.roadmap_id != r.id:
        raise NotFoundError("Topic not found in this roadmap.")
    if r.status != "ready":
        raise ConflictError("This roadmap is not ready yet.")
    return r, node


async def _progress_row(db: AsyncSession, user_id: str, node_id: str) -> RoadmapNodeProgress:
    row = await db.get(RoadmapNodeProgress, (user_id, node_id))
    if row is None:
        row = RoadmapNodeProgress(user_id=user_id, node_id=node_id, session_ids=[], meta={})
        db.add(row)
    return row


async def set_node_status(db: AsyncSession, user_id: str, roadmap_id: str, node_id: str,
                          data: NodeStatusIn) -> NodeOut:
    r, node = await _node(db, user_id, roadmap_id, node_id)
    row = await _progress_row(db, user_id, node.id)
    row.manual_status = data.status
    row.meta = {**(row.meta or {}), "manual_set_at": utcnow().isoformat()}
    await follow(db, user_id, r.id)
    await db.commit()
    nodes = await _nodes(db, r.id)
    return next(s for s in await _node_states(db, user_id, nodes) if s.id == node.id)


async def start_node_session(db: AsyncSession, user: User, roadmap_id: str, node_id: str) -> NodeSessionOut:
    """Study a roadmap topic: grounded in the student's own course when one of its concepts matches,
    otherwise a general-knowledge session clearly labelled as such."""
    r, node = await _node(db, user.id, roadmap_id, node_id)
    concept = (await _concept_matches(db, user.id, [node])).get(node.id)
    goal = f"Understand {node.title} for the {r.role} roadmap. {node.description}".strip()[:300]
    if concept:
        session = await study_service.start_session(db, user, SessionCreate(
            course_id=concept.course_id, concept_id=concept.id, goal=goal))
    else:
        session = await study_service.start_session(db, user, SessionCreate(topic=node.title[:160], goal=goal))
    row = await _progress_row(db, user.id, node.id)
    row.session_ids = [*(row.session_ids or []), session.id][-20:]
    if concept:
        row.concept_id = concept.id
    await follow(db, user.id, r.id)
    await db.commit()
    return NodeSessionOut(session_id=session.id, course_id=session.course_id, topic=session.topic, goal=session.goal,
                          knowledge_mode=session.knowledge_mode)
