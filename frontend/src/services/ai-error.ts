import type { ApiErrorCode } from './http-client'
import { ApiError } from './http-client'

export type AiErrorInfo = {
  /** Safe user-facing message. Empty string for 'cancelled' — show nothing. */
  userMessage: string
  code: ApiErrorCode | 'unknown'
  /** True when the user may retry the same operation */
  retryable: boolean
  /** If non-zero, the user should wait this many ms before retrying */
  retryAfterMs: number
}

// ---------------------------------------------------------------------------
// Safe per-code messages
//
// Rules:
//  • server-error / service-unavailable: never relay the server's message —
//    it may contain provider names (Groq, OpenAI), stack traces, or keys.
//  • rate-limited from our own service code is safe; from a raw 429 we use
//    a fixed message since the server body is untrusted.
//  • bad-request / validation: server detail could expose internals — use
//    a generic message.
//  • timeout / network-error / cancelled: generated by http-client.ts, safe.
// ---------------------------------------------------------------------------

const SAFE_MESSAGES: Partial<Record<ApiErrorCode, string>> = {
  'rate-limited': 'Too many requests. Please wait a moment before trying again.',
  'timeout': 'The request timed out. Please try again.',
  'server-error': 'The AI service is temporarily unavailable. Try again in a moment.',
  'service-unavailable': 'The service is temporarily unavailable. Try again in a moment.',
  'network-error': 'A network error occurred. Check your connection and try again.',
  'bad-request': 'The request could not be completed. Check your input and try again.',
  'validation': 'Some of your input could not be accepted. Check the form and try again.',
  'payload-too-large': 'The content is too large to process. Try reducing the amount of selected material.',
  'unauthorized': 'Your session has expired. Please sign in again.',
  'forbidden': 'You do not have permission to perform this action.',
  'not-found': 'The resource was not found. It may have been deleted.',
  'conflict': 'This action has already been completed.',
  'cancelled': '',
}

const RETRYABLE_CODES = new Set<ApiErrorCode>([
  'rate-limited',
  'timeout',
  'server-error',
  'service-unavailable',
  'network-error',
  'unknown',
])

export function classifyAiError(error: unknown): AiErrorInfo {
  if (error instanceof ApiError) {
    const code = error.code
    const userMessage = SAFE_MESSAGES[code] ?? 'Something went wrong. Please try again.'
    const retryable = RETRYABLE_CODES.has(code)

    // For rate-limited errors that our own services annotate with a wait time
    // (e.g. chat service sets the seconds in its message), extract it.
    // We only do this for ApiErrors WE created (rate-limited, timeout) —
    // never for messages that came from server response bodies.
    let retryAfterMs = 0
    if (code === 'rate-limited') {
      const match = /wait (\d+) second/i.exec(error.message)
      if (match) {
        retryAfterMs = parseInt(match[1], 10) * 1000
      } else {
        retryAfterMs = 60_000
      }
    }

    return { userMessage, code, retryable, retryAfterMs }
  }

  // Non-ApiError (unexpected throw, programming errors, etc.)
  // Never expose the message — it could contain anything.
  return {
    userMessage: 'Something went wrong. Please try again.',
    code: 'unknown',
    retryable: true,
    retryAfterMs: 0,
  }
}

/** Returns a human-readable "wait N seconds" label, or empty string if retryAfterMs is 0. */
export function formatRetryAfter(retryAfterMs: number): string {
  if (!retryAfterMs) return ''
  const secs = Math.ceil(retryAfterMs / 1000)
  return `${secs} second${secs !== 1 ? 's' : ''}`
}
